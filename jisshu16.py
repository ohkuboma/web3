import pandas as pd
import plotly.express as px

# ここは自分の環境に合わせてパスを変えてOK
# （Colabでファイルをアップしたなら "california_housing_test.csv" だけで大丈夫なはず）
df = pd.read_csv("california_housing_test.csv")

df.head()

"""#### (2) 使う列だけ抜き出す ＋ describe"""

cols = ["median_income", "housing_median_age", "median_house_value"]
df_sub = df[cols]

summary = df_sub.describe().round(2)
summary

"""#### (3) Plotly で散布図を描く"""

fig = px.scatter(
    df_sub,
    x="median_income",
    y="median_house_value",
    title="所得と住宅価格の関係（California housing）",
    labels={
        "median_income": "世帯所得（中央値）",
        "median_house_value": "住宅価格（中央値）",
    },
    opacity=0.5,
)
fig.show()

"""#### (4) グラフ＋表を 1 枚の HTML に書き出す"""

# グラフ部分を HTML 文字列として取得
plot_html = fig.to_html(full_html=False, include_plotlyjs="cdn")

# describe の表を HTML テーブルに変換
